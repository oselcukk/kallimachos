"""Reading batches ("chunks") with LPT-balanced groups.

Files: ``chunks/<n>/list.json``, ``chunks/<n>/groups.json``, ``chunks/<n>/log.md`` (generated by
commands; agents do not edit the log by hand).
"""

from __future__ import annotations

import datetime as _dt
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from kallimachos.archive.catalog import Catalog
from kallimachos.config.schema import ProcessConfig
from kallimachos.interfaces import CatalogEntry, CatalogStatus, UsageError, WorkKind, WorkState
from kallimachos.paths import DataLayout
from kallimachos.process import status as status_mod
from kallimachos.state import store
from kallimachos.state.machine import at_least

BOOK_KINDS: frozenset[WorkKind] = frozenset({WorkKind.BOOK, WorkKind.THESIS})
ACTIVE_STATUSES: frozenset[CatalogStatus] = frozenset(
    {CatalogStatus.STORED, CatalogStatus.EXISTING, CatalogStatus.IN_BOOK}
)


@dataclass
class Chunk:
    number: int
    channel: str
    eids: list[str] = field(default_factory=list)
    groups: list[list[str]] = field(default_factory=list)
    books: list[str] = field(
        default_factory=list
    )  # eids with pages > book_pages, handled separately


def lpt_groups(items: Sequence[tuple[str, int]], group_size: int) -> list[list[str]]:
    """Longest-processing-time first assignment of (eid, pages) into ``group_size``-sized groups.

    The number of groups is ``ceil(n / group_size)``; every group takes at most ``group_size``
    items; each item goes to the lightest group (by total pages) that still has room.
    """
    if group_size < 1:
        raise UsageError("chunk.group_size must be >= 1")
    if not items:
        return []
    count = -(-len(items) // group_size)
    groups: list[list[str]] = [[] for _ in range(count)]
    loads = [0] * count
    for eid, pages in sorted(items, key=lambda it: (-max(it[1], 1), it[0])):
        open_groups = [i for i in range(count) if len(groups[i]) < group_size]
        target = min(open_groups, key=lambda i: (loads[i], i))
        groups[target].append(eid)
        loads[target] += max(pages, 1)
    return groups


def chunk_dir(layout: DataLayout, number: int) -> Path:
    return layout.chunks_dir / str(number)


def chunk_numbers(layout: DataLayout) -> list[int]:
    if not layout.chunks_dir.is_dir():
        return []
    return sorted(
        int(p.name)
        for p in layout.chunks_dir.iterdir()
        if p.is_dir() and re.fullmatch(r"[0-9]+", p.name)
    )


def eid_of(entry: CatalogEntry) -> str | None:
    return entry.sha256[:12] if entry.sha256 else None


def _folder_of(entry: CatalogEntry) -> str:
    if entry.folder:
        return entry.folder
    if entry.path:
        parts = Path(entry.path).parts
        return "/".join(parts[:-1])
    return ""


def _is_book(entry: CatalogEntry, cfg: ProcessConfig) -> bool:
    return entry.kind in BOOK_KINDS or bool(entry.pages and entry.pages > cfg.book_pages)


def _work_row(entry: CatalogEntry, eid: str) -> dict[str, Any]:
    return {
        "eid": eid,
        "path": entry.path,
        "folder": _folder_of(entry),
        "pages": entry.pages,
        "year": entry.year,
        "authors": list(entry.authors),
        "title": entry.title,
    }


def create_chunk(
    catalog: Catalog,
    layout: DataLayout,
    cfg: ProcessConfig,
    *,
    channel: str,
    size: int,
    now: _dt.datetime | None = None,
) -> Chunk:
    """Select the next ``size`` works of ``channel`` not in an earlier chunk and write the files.

    Books (``kind`` book/thesis or more pages than ``process.book_pages``) are listed separately
    and do not count towards ``size``. Groups are LPT-balanced within each sub-folder.
    """
    if size < 1:
        raise UsageError("--size must be >= 1")
    taken: set[str] = set()
    for n in chunk_numbers(layout):
        prev = load_chunk(layout, n)
        taken.update(prev.eids)
        taken.update(prev.books)
    pool: list[tuple[CatalogEntry, str]] = []
    for entry in catalog.entries():
        eid = eid_of(entry)
        if eid is None or eid in taken or entry.status not in ACTIVE_STATUSES:
            continue
        if entry.channel != channel and not _folder_of(entry).startswith(channel):
            continue
        pool.append((entry, eid))
    pool.sort(
        key=lambda it: (
            _folder_of(it[0]),
            it[0].year or 9999,
            " ".join(it[0].authors).lower(),
            it[1],
        )
    )
    books = [(e, eid) for e, eid in pool if _is_book(e, cfg)]
    works = [(e, eid) for e, eid in pool if not _is_book(e, cfg)]
    selected = works[:size]
    remaining = len(works) - len(selected)

    groups: list[list[str]] = []
    by_folder: dict[str, list[tuple[str, int]]] = {}
    for entry, eid in selected:
        by_folder.setdefault(_folder_of(entry), []).append((eid, entry.pages or 0))
    for folder in sorted(by_folder):
        groups.extend(lpt_groups(by_folder[folder], cfg.chunk.group_size))

    number = (chunk_numbers(layout) or [0])[-1] + 1
    chunk = Chunk(
        number=number,
        channel=channel,
        eids=[eid for _, eid in selected],
        groups=groups,
        books=[eid for _, eid in books],
    )
    stamp = (now or _dt.datetime.now(tz=_dt.UTC)).isoformat(timespec="seconds")
    d = chunk_dir(layout, number)
    store.write_json_atomic(
        d / "list.json",
        {
            "chunk": number,
            "channel": channel,
            "created_at": stamp,
            "works": [_work_row(e, eid) for e, eid in selected],
            "books": [_work_row(e, eid) for e, eid in books],
            "remaining": remaining,
        },
    )
    store.write_json_atomic(d / "groups.json", groups)
    lines = [
        f"# Chunk {number} ({channel})",
        "",
        f"Created {stamp}: {len(selected)} work(s), {len(books)} book(s) set aside, "
        f"{remaining} remaining in the channel.",
        "",
        "| group | eids |",
        "|---|---|",
    ]
    lines += [f"| {i} | {', '.join(g)} |" for i, g in enumerate(groups, start=1)]
    lines += ["", "## Log", ""]
    store.write_text_atomic(d / "log.md", "\n".join(lines) + "\n")
    return chunk


def load_chunk(layout: DataLayout, number: int) -> Chunk:
    d = chunk_dir(layout, number)
    data = store.read_json(d / "list.json")
    if not isinstance(data, dict):
        raise UsageError(f"chunk {number} does not exist ({d / 'list.json'})")
    groups = store.read_json(d / "groups.json", default=[])
    return Chunk(
        number=number,
        channel=str(data.get("channel", "")),
        eids=[str(w["eid"]) for w in data.get("works", [])],
        groups=[[str(e) for e in g] for g in groups] if isinstance(groups, list) else [],
        books=[str(w["eid"]) for w in data.get("books", [])],
    )


def all_chunks(layout: DataLayout) -> list[Chunk]:
    return [load_chunk(layout, n) for n in chunk_numbers(layout)]


def active_chunks(layout: DataLayout) -> list[Chunk]:
    """Chunks with at least one eid below ``note_written`` (used by the ``links --apply`` gate)."""
    states = status_mod.current_states(layout)
    out: list[Chunk] = []
    for chunk in all_chunks(layout):
        for eid in chunk.eids:
            entry = states.get(eid)
            if entry is None or not at_least(entry.state, WorkState.NOTE_WRITTEN):
                out.append(chunk)
                break
    return out


def chunks_containing(layout: DataLayout, eid: str) -> list[Chunk]:
    return [c for c in all_chunks(layout) if eid in c.eids or eid in c.books]


def log_event(
    layout: DataLayout, eids: Iterable[str], text: str, *, now: _dt.datetime | None = None
) -> list[Path]:
    """Append one line to ``chunks/<n>/log.md`` of every chunk that contains one of ``eids``.

    Commands call this (``card-write``, ``check``, ``semantic-record``); agents never edit the
    log by hand.
    """
    stamp = (now or _dt.datetime.now(tz=_dt.UTC)).isoformat(timespec="seconds")
    touched: list[Path] = []
    wanted = set(eids)
    for chunk in all_chunks(layout):
        if not wanted & (set(chunk.eids) | set(chunk.books)):
            continue
        path = chunk_dir(layout, chunk.number) / "log.md"
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current and not current.endswith("\n"):
            current += "\n"
        store.write_text_atomic(path, f"{current}- {stamp} {text}\n")
        touched.append(path)
    return touched
