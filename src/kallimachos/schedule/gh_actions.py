"""``.github/workflows/scan.yml.example`` rendering and guidance.

Facts from docs.github.com ("Events that trigger workflows", ``schedule``): the shortest interval
is 5 minutes; runs may be delayed under load, the start of every hour is the busiest time; only the
workflow on the default branch runs on a schedule; in a public repository scheduled workflows are
disabled automatically after 60 days without repository activity. ``workflow_dispatch`` allows a
manual run. The profile and config never enter the repository: they come from secrets.
"""

from __future__ import annotations

import datetime as _dt
import os
from pathlib import Path
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from kallimachos.config.schema import Config
from kallimachos.interfaces import UsageError
from kallimachos.paths import DataLayout
from kallimachos.schedule.base import (
    WEEKDAY_NUMBER,
    JobStatus,
    Runner,
    ScheduleFile,
    default_runner,
    parse_hhmm,
)

WORKFLOW_NAME = "kallimachos-scan.yml"
MARKER = "# Generated by `kallimachos schedule install --backend github`."
EXAMPLE_PATH = Path(".github") / "workflows" / "scan.yml.example"
SECRETS = (
    ("KALLIMACHOS_CONFIG_B64", "base64 of config.yaml (required)"),
    ("KALLIMACHOS_PROFILE_B64", "base64 of profile.yaml (required, approved profile)"),
    ("TELEGRAM_BOT_TOKEN", "only with the Telegram channel (config: env:TELEGRAM_BOT_TOKEN)"),
    ("SMTP_PASSWORD", "only with the e-mail channel (config: env:SMTP_PASSWORD)"),
    ("OPENALEX_API_KEY", "optional (config: env:OPENALEX_API_KEY)"),
    ("ANTHROPIC_API_KEY", "only with model.provider claude (runs `claude -p --bare`)"),
)


def _zone(config: Config) -> _dt.tzinfo:
    if config.timezone:
        try:
            return ZoneInfo(config.timezone)
        except ZoneInfoNotFoundError:
            raise UsageError(f"unknown timezone {config.timezone!r}") from None
    local = _dt.datetime.now().astimezone().tzinfo
    return local or _dt.UTC


def utc_cron(hhmm: str, zone: _dt.tzinfo, weekday: str | None, today: _dt.date) -> str:
    """Local ``HH:MM`` (and weekday) -> a UTC cron expression, using the offset in force on the
    next occurrence after ``today``. GitHub cron is UTC; daylight-saving changes shift it."""
    hour, minute = parse_hhmm(hhmm)
    day = today
    if weekday is not None:
        target = (WEEKDAY_NUMBER[weekday] - 1) % 7  # cron Sunday=0 -> Python Monday=0
        day = today + _dt.timedelta(days=(target - today.weekday()) % 7)
    local = _dt.datetime.combine(day, _dt.time(hour, minute), tzinfo=zone)
    utc = local.astimezone(_dt.UTC)
    dow = str((utc.weekday() + 1) % 7) if weekday is not None else "*"
    return f"{utc.minute} {utc.hour} * * {dow}"


def workflow_yaml(config: Config, *, today: _dt.date | None = None) -> str:
    today = today or _dt.date.today()
    zone = _zone(config)
    sched = config.schedule
    daily = utc_cron(sched.daily_at, zone, None, today)
    weekly = utc_cron(sched.weekly_at, zone, sched.weekly_on, today)
    zone_name = config.timezone or "local time of the machine that rendered this file"
    model = (
        "\n          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}"
        if config.model.provider == "claude"
        else ""
    )
    return f"""{MARKER}
# Copy into a PRIVATE copy of the repository (it runs with your profile); see docs/schedule.md.
name: kallimachos-scan

on:
  schedule:
    # GitHub cron is UTC. daily {sched.daily_at} and weekly {sched.weekly_on} {sched.weekly_at}
    # in {zone_name}. Shortest interval 5 min; runs can be late under load (avoid minute 0).
    - cron: "{daily}"
    - cron: "{weekly}"
  workflow_dispatch:
    inputs:
      kind:
        description: "daily or weekly"
        type: choice
        options: [daily, weekly]
        default: daily

permissions:
  contents: read

concurrency:
  group: kallimachos-scan
  cancel-in-progress: false

jobs:
  scan:
    runs-on: ubuntu-latest
    timeout-minutes: 60
    env:
      KALLIMACHOS_HOME: /home/runner/.local/share/kallimachos
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - name: Install Kallimachos from this repository
        run: python -m pip install .
      - name: Restore state (best effort; personal data stays out of the repository)
        uses: actions/cache@v4
        with:
          path: |
            /home/runner/.local/share/kallimachos/state
            /home/runner/.local/share/kallimachos/runs
            /home/runner/.local/share/kallimachos/weights.json
          key: kallimachos-state-${{{{ github.run_id }}}}
          restore-keys: kallimachos-state-
      - name: Materialize profile and config from secrets
        env:
          CONFIG_B64: ${{{{ secrets.KALLIMACHOS_CONFIG_B64 }}}}
          PROFILE_B64: ${{{{ secrets.KALLIMACHOS_PROFILE_B64 }}}}
        run: |
          mkdir -p "$KALLIMACHOS_HOME"
          printf '%s' "$CONFIG_B64" | base64 -d > "$KALLIMACHOS_HOME/config.yaml"
          printf '%s' "$PROFILE_B64" | base64 -d > "$KALLIMACHOS_HOME/profile.yaml"
      - name: Scan
        env:
          TELEGRAM_BOT_TOKEN: ${{{{ secrets.TELEGRAM_BOT_TOKEN }}}}
          SMTP_PASSWORD: ${{{{ secrets.SMTP_PASSWORD }}}}
          OPENALEX_API_KEY: ${{{{ secrets.OPENALEX_API_KEY }}}}{model}
          EVENT_SCHEDULE: ${{{{ github.event.schedule }}}}
          INPUT_KIND: ${{{{ inputs.kind }}}}
        run: |
          kind="${{INPUT_KIND:-daily}}"
          if [ "$EVENT_SCHEDULE" = "{weekly}" ]; then kind=weekly; fi
          kallimachos run "$kind"
"""


class GitHubActionsBackend:
    name = "gh_actions"

    def __init__(
        self,
        *,
        home: Path | None = None,
        runner: Runner | None = None,
        repo_dir: Path | None = None,
    ) -> None:
        self.repo_dir = repo_dir if repo_dir is not None else Path(os.getcwd())
        self.runner = runner or default_runner

    @property
    def workflow_path(self) -> Path:
        return self.repo_dir / ".github" / "workflows" / WORKFLOW_NAME

    def render(self, config: Config, layout: DataLayout, *, python: str) -> list[ScheduleFile]:
        return [ScheduleFile(self.workflow_path, workflow_yaml(config), "daily")]

    def install(self, files: list[ScheduleFile]) -> None:
        for f in files:
            if f.path.exists() and MARKER not in f.path.read_text(encoding="utf-8"):
                raise UsageError(f"{f.path} exists and was not written by Kallimachos; not touched")
            f.path.parent.mkdir(parents=True, exist_ok=True)
            f.path.write_text(f.content, encoding="utf-8", newline="\n")

    def remove(self, config: Config) -> None:
        path = self.workflow_path
        if path.exists() and MARKER in path.read_text(encoding="utf-8"):
            path.unlink()

    def status(self, config: Config) -> list[JobStatus]:
        path = self.workflow_path
        ok = path.exists() and MARKER in path.read_text(encoding="utf-8")
        detail = f"{path} (run history: GitHub Actions tab or `gh run list`)" if ok else ""
        return [JobStatus("daily", ok, detail=detail), JobStatus("weekly", ok, detail=detail)]

    def guidance(self, config: Config, layout: DataLayout, *, python: str) -> list[str]:
        lines = [
            "Use a PRIVATE copy of the repository: the workflow runs with your profile, and in a "
            "public repository GitHub disables scheduled workflows after 60 days without activity.",
            "Scheduled workflows run only from the default branch; commit the file there.",
            "GitHub cron is UTC; the times above were converted with today's offset "
            "(re-run `schedule install` after a daylight-saving change if the hour matters).",
            "Runs can start late under load; the scan window is wide enough for that.",
            "Add these repository secrets (Settings > Secrets and variables > Actions):",
        ]
        lines += [f"  {name}: {why}" for name, why in SECRETS]
        lines += [
            "  e.g. `base64 < config.yaml | gh secret set KALLIMACHOS_CONFIG_B64` (macOS/Linux)",
            "In the config used on GitHub, reference secrets as env:VAR (no keyring on runners), "
            "and prefer the Telegram or e-mail channel: a Markdown file on the runner is lost.",
            "Start a run by hand from the Actions tab (workflow_dispatch) to test it.",
            "The runner has no `claude`/`codex` CLI: use model.provider none there, or install "
            "the CLI in an extra step (it then authenticates with ANTHROPIC_API_KEY, `--bare`).",
        ]
        if any(
            parse_hhmm(t)[1] == 0 for t in (config.schedule.daily_at, config.schedule.weekly_at)
        ):
            lines.append("Tip: a minute other than :00 avoids the busiest time on GitHub.")
        return lines
